#!/usr/bin/env node
/**
 * Copies PUBLIC_* variables from .env into js/env.js so the browser can read them.
 *
 * Safety rules:
 *   1. Only variables that start with PUBLIC_ are copied.
 *   2. A PUBLIC_ name that looks like a secret stops the script.
 *   3. A value that looks like a real credential stops the script.
 *
 * Usage: node scripts/generate-env.mjs [--env-file .env] [--out js/env.js]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (flag, fallback) => { const i = process.argv.indexOf(flag); return i > -1 ? process.argv[i + 1] : fallback; };
const envFile = resolve(root, arg('--env-file', '.env'));
const outFile = resolve(root, arg('--out', 'js/env.js'));

const SECRET_NAME = /(SECRET|TOKEN|PASSWORD|PRIVATE|CREDENTIAL|API_KEY|(^|_)KEY$)/i;
const SECRET_VALUE = /^(sk-|ghp_|github_pat_|AKIA|xox[abp]-)|^eyJ[\w-]+\.[\w-]+\./;

function parse(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith('#')) continue;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return out;
}

let source = envFile;
if (!existsSync(source)) {
  source = resolve(root, '.env.example');
  console.warn(`! ${envFile} not found, using .env.example. Run: cp .env.example .env`);
}

const vars = parse(readFileSync(source, 'utf8'));
const pub = {};
const errors = [];

for (const [name, value] of Object.entries(vars)) {
  if (!name.startsWith('PUBLIC_')) continue;
  const short = name.slice('PUBLIC_'.length);
  if (SECRET_NAME.test(short)) errors.push(`${name}: the name looks like a secret. Secrets belong in the backend.`);
  else if (SECRET_VALUE.test(value)) errors.push(`${name}: the value looks like a real credential.`);
  else pub[short] = value;
}

if (errors.length) {
  console.error('\nRefusing to write ' + outFile + ':\n  - ' + errors.join('\n  - ') + '\n');
  process.exit(1);
}

const body = JSON.stringify(Object.fromEntries(Object.entries(pub).sort()), null, 2);
writeFileSync(outFile, `/* GENERATED by scripts/generate-env.mjs. Do not edit. Public values only, no secrets. */\nwindow.__ENV__ = Object.freeze(${body});\n`);
const skipped = Object.keys(vars).filter(k => !k.startsWith('PUBLIC_'));
console.log(`Wrote ${Object.keys(pub).length} public value(s) to ${outFile}` + (skipped.length ? `\nSkipped ${skipped.length} non-PUBLIC_ variable(s): ${skipped.join(', ')}` : ''));
