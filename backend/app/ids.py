"""Reusable identifier and timestamp helpers.

All identifiers and timestamps are generated by the backend; identifiers that
originate from an external system or an AI model are never trusted as primary
keys. Timestamps are always timezone-aware UTC (serialised as ISO-8601).
"""

from datetime import datetime, timezone
from uuid import UUID, uuid4


def utcnow() -> datetime:
    """Return the current time as a timezone-aware UTC datetime."""
    return datetime.now(timezone.utc)


def new_uuid() -> UUID:
    """Return a new random UUID4."""
    return uuid4()


def new_id(prefix: str) -> str:
    """Return a new prefixed identifier, e.g. ``new_id("evt") -> "evt_<hex>"``."""
    return f"{prefix}_{uuid4().hex}"
